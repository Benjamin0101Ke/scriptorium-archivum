-- Las tablas de fase futura se incluyen segun el modelo y quedan disponibles para su fase

BEGIN;
SET LOCAL client_encoding = 'UTF8';

CREATE TABLE public.personas (
    id_persona integer GENERATED BY DEFAULT AS IDENTITY,
    nombres varchar(100) NOT NULL,
    apellidos varchar(100) NOT NULL,
    identificador_institucional varchar(30),
    CONSTRAINT pk_personas PRIMARY KEY (id_persona),
    CONSTRAINT uq_personas_identificador_institucional UNIQUE (identificador_institucional),
    CONSTRAINT ck_personas_nombres CHECK (nombres ~ '[^[:space:]]'),
    CONSTRAINT ck_personas_apellidos CHECK (apellidos ~ '[^[:space:]]'),
    CONSTRAINT ck_personas_identificador CHECK (identificador_institucional IS NULL OR (identificador_institucional = btrim(identificador_institucional) AND identificador_institucional ~ '[^[:space:]]'))
);

CREATE TABLE public.roles (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY,
    nombre varchar(50) NOT NULL,
    descripcion text,
    activo boolean DEFAULT true NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id_rol),
    CONSTRAINT uq_roles_nombre UNIQUE (nombre),
    CONSTRAINT ck_roles_nombre CHECK (nombre ~ '[^[:space:]]')
);

CREATE TABLE public.usuarios (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY,
    id_persona integer NOT NULL,
    correo_institucional varchar(150) NOT NULL,
    estado varchar(20) DEFAULT 'Habilitada' NOT NULL,
    fecha_alta timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    proveedor_identidad varchar(50),
    hash_contrasena text NOT NULL,
    id_rol integer NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuarios_persona UNIQUE (id_persona),
    CONSTRAINT uq_usuarios_correo_institucional UNIQUE (correo_institucional),
    CONSTRAINT fk_usuarios_persona FOREIGN KEY (id_persona)
        REFERENCES public.personas (id_persona),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol)
        REFERENCES public.roles (id_rol),
    CONSTRAINT ck_usuarios_correo CHECK (correo_institucional = lower(btrim(correo_institucional)) AND correo_institucional ~ '[^[:space:]]'),
    CONSTRAINT ck_usuarios_estado CHECK (estado IN ('Habilitada', 'Deshabilitada')),
    CONSTRAINT ck_usuarios_hash CHECK (hash_contrasena ~ '[^[:space:]]')
);

CREATE TABLE IF NOT EXISTS public.carreras (
    id_carrera integer GENERATED BY DEFAULT AS IDENTITY,
    codigo_carrera varchar(20) NOT NULL,
    nombre varchar(120) NOT NULL,
    activa boolean DEFAULT true NOT NULL,
    CONSTRAINT pk_carreras PRIMARY KEY (id_carrera),
    CONSTRAINT uq_carreras_codigo_carrera UNIQUE (codigo_carrera),
    CONSTRAINT uq_carreras_nombre UNIQUE (nombre),
    CONSTRAINT ck_carreras_codigo CHECK (codigo_carrera ~ '[^[:space:]]'),
    CONSTRAINT ck_carreras_nombre CHECK (nombre ~ '[^[:space:]]')
);

CREATE TABLE IF NOT EXISTS public.tipos_trabajo (
    id_tipo_trabajo integer GENERATED BY DEFAULT AS IDENTITY,
    nombre varchar(60) NOT NULL,
    descripcion text,
    requiere_aprobacion_academica boolean DEFAULT false NOT NULL,
    CONSTRAINT pk_tipos_trabajo PRIMARY KEY (id_tipo_trabajo),
    CONSTRAINT uq_tipos_trabajo_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipos_trabajo_nombre CHECK (nombre ~ '[^[:space:]]')
);

CREATE TABLE IF NOT EXISTS public.areas_tematicas (
    id_area integer GENERATED BY DEFAULT AS IDENTITY,
    nombre varchar(100) NOT NULL,
    descripcion text,
    activa boolean DEFAULT true NOT NULL,
    CONSTRAINT pk_areas_tematicas PRIMARY KEY (id_area),
    CONSTRAINT uq_areas_tematicas_nombre UNIQUE (nombre),
    CONSTRAINT ck_areas_tematicas_nombre CHECK (nombre ~ '[^[:space:]]')
);

-- Estructura reservada para una fase posterior
CREATE TABLE public.solicitudes (
    id_solicitud integer GENERATED BY DEFAULT AS IDENTITY,
    id_usuario_solicitante integer NOT NULL,
    id_carrera integer NOT NULL,
    id_tipo_trabajo integer NOT NULL,
    titulo_provisional varchar(250) NOT NULL,
    descripcion text NOT NULL,
    fecha_presentacion timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado varchar(30) NOT NULL,
    plazo_correccion timestamptz,
    CONSTRAINT pk_solicitudes PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitudes_usuario_solicitante FOREIGN KEY (id_usuario_solicitante)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT fk_solicitudes_carrera FOREIGN KEY (id_carrera)
        REFERENCES public.carreras (id_carrera),
    CONSTRAINT fk_solicitudes_tipo_trabajo FOREIGN KEY (id_tipo_trabajo)
        REFERENCES public.tipos_trabajo (id_tipo_trabajo),
    CONSTRAINT ck_solicitudes_datos CHECK (titulo_provisional ~ '[^[:space:]]' AND descripcion ~ '[^[:space:]]' AND estado ~ '[^[:space:]]'),
    CONSTRAINT ck_solicitudes_plazo CHECK (plazo_correccion IS NULL OR plazo_correccion >= fecha_presentacion)
);

CREATE TABLE public.trabajos (
    id_trabajo integer GENERATED BY DEFAULT AS IDENTITY,
    codigo varchar(30) NOT NULL,
    id_tipo_trabajo integer NOT NULL,
    id_carrera integer NOT NULL,
    id_solicitud integer,
    id_entrega_final integer,
    titulo varchar(250) NOT NULL,
    anio smallint NOT NULL,
    resumen text NOT NULL,
    objetivos text,
    resultados text,
    estado_publicacion varchar(20) DEFAULT 'Borrador' NOT NULL,
    nivel_acceso varchar(20),
    fecha_habilitacion timestamptz,
    fecha_publicacion timestamptz,
    fecha_retiro timestamptz,
    motivo_retiro text,
    fecha_registro timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    referencia_deposito_ues text,
    deposito_verificado_por integer,
    deposito_verificado_en timestamptz,
    id_usuario_retira integer,
    CONSTRAINT pk_trabajos PRIMARY KEY (id_trabajo),
    CONSTRAINT uq_trabajos_codigo UNIQUE (codigo),
    CONSTRAINT uq_trabajos_solicitud UNIQUE (id_solicitud),
    CONSTRAINT uq_trabajos_entrega_final UNIQUE (id_entrega_final),
    CONSTRAINT fk_trabajos_tipo_trabajo FOREIGN KEY (id_tipo_trabajo)
        REFERENCES public.tipos_trabajo (id_tipo_trabajo),
    CONSTRAINT fk_trabajos_carrera FOREIGN KEY (id_carrera)
        REFERENCES public.carreras (id_carrera),
    CONSTRAINT fk_trabajos_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES public.solicitudes (id_solicitud),
    CONSTRAINT fk_trabajos_deposito_verificado_por FOREIGN KEY (deposito_verificado_por)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT fk_trabajos_usuario_retira FOREIGN KEY (id_usuario_retira)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT ck_trabajos_textos CHECK (codigo ~ '[^[:space:]]' AND titulo ~ '[^[:space:]]' AND resumen ~ '[^[:space:]]'),
    CONSTRAINT ck_trabajos_anio CHECK (anio BETWEEN 1000 AND 9999),
    CONSTRAINT ck_trabajos_estado CHECK (estado_publicacion IN ('Borrador', 'En revisión', 'Publicado', 'Retirado')),
    CONSTRAINT ck_trabajos_publicacion CHECK (estado_publicacion <> 'Publicado' OR (fecha_publicacion IS NOT NULL AND id_entrega_final IS NOT NULL)),
    CONSTRAINT ck_trabajos_retiro CHECK (estado_publicacion <> 'Retirado' OR (fecha_retiro IS NOT NULL AND id_usuario_retira IS NOT NULL AND motivo_retiro IS NOT NULL AND motivo_retiro ~ '[^[:space:]]')),
    CONSTRAINT ck_trabajos_referencia_ues CHECK (referencia_deposito_ues IS NULL OR referencia_deposito_ues ~ '[^[:space:]]'),
    CONSTRAINT ck_trabajos_deposito_verificado CHECK ((deposito_verificado_por IS NULL AND deposito_verificado_en IS NULL)
        OR (deposito_verificado_por IS NOT NULL AND deposito_verificado_en IS NOT NULL AND referencia_deposito_ues IS NOT NULL))
);

CREATE TABLE public.participaciones (
    id_participacion integer GENERATED BY DEFAULT AS IDENTITY,
    id_persona integer NOT NULL,
    id_trabajo integer NOT NULL,
    calidad_participacion varchar(30) NOT NULL,
    orden_autoria smallint,
    CONSTRAINT pk_participaciones PRIMARY KEY (id_participacion),
    CONSTRAINT uq_participaciones_persona_trabajo_calidad_participacion UNIQUE (id_persona, id_trabajo, calidad_participacion),
    CONSTRAINT fk_participaciones_persona FOREIGN KEY (id_persona)
        REFERENCES public.personas (id_persona),
    CONSTRAINT fk_participaciones_trabajo FOREIGN KEY (id_trabajo)
        REFERENCES public.trabajos (id_trabajo),
    CONSTRAINT ck_participaciones_calidad CHECK (calidad_participacion ~ '[^[:space:]]'),
    CONSTRAINT ck_participaciones_orden_autoria CHECK (orden_autoria IS NULL OR (orden_autoria > 0 AND calidad_participacion = 'Autor'))
);

CREATE TABLE public.trabajos_areas (
    id_trabajo_area integer GENERATED BY DEFAULT AS IDENTITY,
    id_trabajo integer NOT NULL,
    id_area integer NOT NULL,
    CONSTRAINT pk_trabajos_areas PRIMARY KEY (id_trabajo_area),
    CONSTRAINT uq_trabajos_areas_trabajo_area UNIQUE (id_trabajo, id_area),
    CONSTRAINT fk_trabajos_areas_trabajo FOREIGN KEY (id_trabajo)
        REFERENCES public.trabajos (id_trabajo),
    CONSTRAINT fk_trabajos_areas_area FOREIGN KEY (id_area)
        REFERENCES public.areas_tematicas (id_area)
);

CREATE TABLE public.palabras_clave_trabajo (
    id_palabra_trabajo integer GENERATED BY DEFAULT AS IDENTITY,
    id_trabajo integer NOT NULL,
    termino varchar(80) NOT NULL,
    CONSTRAINT pk_palabras_clave_trabajo PRIMARY KEY (id_palabra_trabajo),
    CONSTRAINT uq_palabras_clave_trabajo_trabajo_termino UNIQUE (id_trabajo, termino),
    CONSTRAINT fk_palabras_clave_trabajo_trabajo FOREIGN KEY (id_trabajo)
        REFERENCES public.trabajos (id_trabajo),
    CONSTRAINT ck_palabras_clave_trabajo_termino CHECK (termino = btrim(termino) AND termino ~ '[^[:space:]]')
);

CREATE TABLE public.permisos_trabajo (
    id_permiso integer GENERATED BY DEFAULT AS IDENTITY,
    id_usuario integer NOT NULL,
    id_trabajo integer NOT NULL,
    nivel_permiso varchar(30) NOT NULL,
    activo boolean DEFAULT true NOT NULL,
    fecha_asignacion timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_permisos_trabajo PRIMARY KEY (id_permiso),
    CONSTRAINT uq_permisos_trabajo_usuario_trabajo UNIQUE (id_usuario, id_trabajo),
    CONSTRAINT fk_permisos_trabajo_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT fk_permisos_trabajo_trabajo FOREIGN KEY (id_trabajo)
        REFERENCES public.trabajos (id_trabajo),
    CONSTRAINT ck_permisos_trabajo_nivel CHECK (nivel_permiso ~ '[^[:space:]]')
);

CREATE TABLE public.entregas (
    id_entrega integer GENERATED BY DEFAULT AS IDENTITY,
    id_trabajo integer NOT NULL,
    numero_version integer NOT NULL,
    id_usuario_envia integer NOT NULL,
    fecha_envio timestamptz,
    fecha_deposito date,
    estado varchar(30) DEFAULT 'Pendiente' NOT NULL,
    nota_cambios text,
    referencia_conformidad text,
    verificado_por integer,
    verificado_en timestamptz,
    difundir_ficha_habilitado boolean DEFAULT false NOT NULL,
    leer_pdf_habilitado boolean DEFAULT false NOT NULL,
    descargar_pdf_habilitado boolean DEFAULT false NOT NULL,
    CONSTRAINT pk_entregas PRIMARY KEY (id_entrega),
    CONSTRAINT uq_entregas_trabajo_entrega UNIQUE (id_trabajo, id_entrega),
    CONSTRAINT uq_entregas_trabajo_numero_version UNIQUE (id_trabajo, numero_version),
    CONSTRAINT fk_entregas_trabajo FOREIGN KEY (id_trabajo)
        REFERENCES public.trabajos (id_trabajo),
    CONSTRAINT fk_entregas_usuario_envia FOREIGN KEY (id_usuario_envia)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT fk_entregas_verificado_por FOREIGN KEY (verificado_por)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT ck_entregas_version CHECK (numero_version > 0),
    CONSTRAINT ck_entregas_estado CHECK (estado IN ('Pendiente', 'Verificado', 'Sustituido')),
    CONSTRAINT ck_entregas_datos_verificacion CHECK ((referencia_conformidad IS NULL AND verificado_por IS NULL AND verificado_en IS NULL)
        OR (referencia_conformidad IS NOT NULL AND referencia_conformidad ~ '[^[:space:]]' AND verificado_por IS NOT NULL AND verificado_en IS NOT NULL)),
    CONSTRAINT ck_entregas_estado_verificado CHECK (estado <> 'Verificado' OR verificado_en IS NOT NULL)
);

CREATE TABLE public.recursos_digitales (
    id_recurso integer GENERATED BY DEFAULT AS IDENTITY,
    id_entrega integer,
    clase varchar(10) NOT NULL,
    ubicacion text NOT NULL,
    nombre varchar(255),
    tipo_formato varchar(100),
    tamano_bytes bigint,
    estado_carga varchar(20),
    id_trabajo integer NOT NULL,
    descripcion text,
    difusion_habilitada boolean DEFAULT false NOT NULL,
    CONSTRAINT pk_recursos_digitales PRIMARY KEY (id_recurso),
    CONSTRAINT fk_recursos_digitales_trabajo FOREIGN KEY (id_trabajo)
        REFERENCES public.trabajos (id_trabajo),
    CONSTRAINT fk_recursos_digitales_entrega_mismo_trabajo FOREIGN KEY (id_trabajo, id_entrega)
        REFERENCES public.entregas (id_trabajo, id_entrega),
    CONSTRAINT ck_recursos_digitales_clase CHECK (clase IN ('PDF', 'REF_UES', 'ENLACE')),
    CONSTRAINT ck_recursos_digitales_ubicacion CHECK (ubicacion ~ '[^[:space:]]'),
    CONSTRAINT ck_recursos_digitales_entrega CHECK (clase = 'ENLACE' OR id_entrega IS NOT NULL),
    CONSTRAINT ck_recursos_digitales_tamano CHECK (tamano_bytes IS NULL OR (clase = 'PDF' AND tamano_bytes > 0)),
    CONSTRAINT ck_recursos_digitales_estado_carga CHECK ((clase = 'PDF' AND estado_carga IS NOT NULL AND estado_carga IN ('Pendiente', 'Disponible', 'Fallido'))
        OR (clase <> 'PDF' AND estado_carga IS NULL)),
    CONSTRAINT ck_recursos_digitales_enlace CHECK (clase <> 'ENLACE' OR (ubicacion ~* '^https://[^[:space:]/?#]+'
        AND tipo_formato IS NOT NULL AND tipo_formato ~ '[^[:space:]]'
        AND descripcion IS NOT NULL AND descripcion ~ '[^[:space:]]')),
    CONSTRAINT ck_recursos_digitales_difusion CHECK (clase = 'ENLACE' OR NOT difusion_habilitada)
);

CREATE TABLE public.procedimientos_deposito (
    id_procedimiento integer GENERATED BY DEFAULT AS IDENTITY,
    version_procedimiento varchar(20) NOT NULL,
    referencia_documento text NOT NULL,
    fecha_aprobacion date NOT NULL,
    vigente_desde date NOT NULL,
    vigente_hasta date,
    CONSTRAINT pk_procedimientos_deposito PRIMARY KEY (id_procedimiento),
    CONSTRAINT uq_procedimientos_deposito_version_procedimiento UNIQUE (version_procedimiento),
    CONSTRAINT ck_procedimientos_deposito_textos CHECK (version_procedimiento ~ '[^[:space:]]' AND referencia_documento ~ '[^[:space:]]'),
    CONSTRAINT ck_procedimientos_deposito_fecha_aprobacion CHECK (fecha_aprobacion <= vigente_desde),
    CONSTRAINT ck_procedimientos_deposito_periodo_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

CREATE TABLE public.revisiones (
    id_revision integer GENERATED BY DEFAULT AS IDENTITY,
    id_entrega integer NOT NULL,
    id_usuario_revisor integer NOT NULL,
    id_procedimiento integer,
    fecha_inicio timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_cierre timestamptz,
    ambito_revision varchar(20) NOT NULL,
    resultado varchar(30),
    motivo_decision text,
    CONSTRAINT pk_revisiones PRIMARY KEY (id_revision),
    CONSTRAINT fk_revisiones_entrega FOREIGN KEY (id_entrega)
        REFERENCES public.entregas (id_entrega),
    CONSTRAINT fk_revisiones_usuario_revisor FOREIGN KEY (id_usuario_revisor)
        REFERENCES public.usuarios (id_usuario),
    CONSTRAINT fk_revisiones_procedimiento FOREIGN KEY (id_procedimiento)
        REFERENCES public.procedimientos_deposito (id_procedimiento),
    CONSTRAINT ck_revisiones_ambito CHECK (ambito_revision ~ '[^[:space:]]'),
    CONSTRAINT ck_revisiones_fechas CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_inicio),
    CONSTRAINT ck_revisiones_decision CHECK (ambito_revision <> 'Difusión' OR fecha_cierre IS NULL
        OR (resultado IS NOT NULL AND resultado IN ('Favorable', 'Desfavorable')
        AND motivo_decision IS NOT NULL AND motivo_decision ~ '[^[:space:]]'))
);

