CREATE TABLE IF NOT EXISTS public.planes_estudio (
    id_plan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrera integer NOT NULL REFERENCES public.carreras,
    nombre varchar(120) NOT NULL,
    documento_url text,
    activa boolean NOT NULL DEFAULT true,
    UNIQUE(id_carrera,nombre)
);
